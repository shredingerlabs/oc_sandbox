// iconSVG renders one named UI glyph as an inline SVG ("" for unknown
// names — templates never guess an icon).
func iconSVG(name string) template.HTML {
	inner, ok := uiIcons[name]
	if !ok {
		return ""
	}
	return template.HTML(`<svg class="ic" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">` + inner + `</svg>`)
}

// iconFuncs is the shared template func for the inline glyph.
var iconFuncs = template.FuncMap{"icon": iconSVG}
